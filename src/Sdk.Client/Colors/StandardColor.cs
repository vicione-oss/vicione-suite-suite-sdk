namespace Sdk.Client.Colors;

/// <summary>
/// Specifies a set of standard, predefined colors.
/// </summary>
public enum StandardColor
{
    /// <summary>
    /// Represents the standard green color.
    /// </summary>
    Green,

    /// <summary>
    /// Represents a lighter shade of the standard green color.
    /// </summary>
    LightGreen,

    /// <summary>
    /// Represents the standard blue color.
    /// </summary>
    Blue,

    /// <summary>
    /// Represents the standard orange color.
    /// </summary>
    Orange,

    /// <summary>
    /// Represents the standard red color.
    /// </summary>
    Red
}
