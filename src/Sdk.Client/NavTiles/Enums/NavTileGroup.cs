namespace Sdk.Client.NavTiles.Enums;

/// <summary>
/// Specifies the group a navigation tile belongs to.
/// </summary>
public enum NavTileGroup
{
    /// <summary>
    /// The tile belongs to the main applications group.
    /// </summary>
    Applications,

    /// <summary>
    /// The tile belongs to the administration or settings group.
    /// </summary>
    Administration,

    /// <summary>
    /// The tile belongs to the user's favorites group.
    /// </summary>
    Favorites
}
